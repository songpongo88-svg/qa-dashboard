export function signaturePaymentPdfLargeFontPatch() {
  return {
    name: "signature-payment-pdf-large-font",
    transform(code, id) {
      if (!id.replace(/\\/g, "/").endsWith("/src/SignatureCenterMockup.tsx")) return null;
      if (!code.includes('section("1. PAYMENT SUMMARY")')) return null;

      let next = code;

      // Section 1: make the payment summary readable at 100% PDF zoom while preserving its layout.
      const section1Start = next.indexOf('section("1. PAYMENT SUMMARY")');
      const section2Start = next.indexOf('section("2. AGENT MONTHLY RANKING & PAYMENT DETAILS")', section1Start);
      if (section1Start >= 0 && section2Start > section1Start) {
        let block = next.slice(section1Start, section2Start);

        // Summary labels such as Payment Period / Paid Agents / Team Cases / Average QA.
        block = block.replace(
          /text\(item\.label,\s*x \+ 1\.2,\s*yy \+ 3\.7,\s*\d+(?:\.\d+)?,\s*false,\s*muted\);/g,
          'text(item.label, x + 1.2, yy + 3.7, 8.2, false, muted);'
        );

        // Summary values such as July 2026 / 13 / 130 / 88.51 / B / 10,100 / READY TO EXPORT.
        block = block.replace(
          /text\(item\.value,\s*x \+ 1\.2,\s*yy \+ 9\.4,\s*\d+(?:\.\d+)?,\s*true,\s*item\.color \|\| black\);/g,
          'text(item.value, x + 1.2, yy + 9.4, 11.0, true, item.color || black);'
        );

        // Keep badge text readable if an older build still renders the status as a badge.
        block = block.replace(
          /text\(label,\s*x \+ 1\.2 \+ badgeW \/ 2,\s*yy \+ 9\.5,\s*\d+(?:\.\d+)?,\s*true,\s*green,/g,
          'text(label, x + 1.2 + badgeW / 2, yy + 9.5, 8.2, true, green,'
        );

        next = next.slice(0, section1Start) + block + next.slice(section2Start);
      }

      // Section 2: force every ranking-table font rule regardless of its previous numeric value.
      const rankingStart = next.indexOf('section("2. AGENT MONTHLY RANKING & PAYMENT DETAILS")');
      const section3Start = next.indexOf('section("3. TEAM TOPIC PERFORMANCE")', rankingStart);
      if (rankingStart >= 0 && section3Start > rankingStart) {
        let block = next.slice(rankingStart, section3Start);

        // Header: Seq / Agent / Document Ref. / Cases / Avg / Grade / Incentive / Status
        block = block.replace(
          /size:\s*label\s*===\s*"Document Ref\."\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: label === "Document Ref." ? 10.3 : 11.0,'
        );

        // Body: Agent, Document Ref. and every numeric/payment column.
        block = block.replace(
          /size:\s*colIndex\s*===\s*1\s*\?\s*\d+(?:\.\d+)?\s*:\s*colIndex\s*===\s*2\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: colIndex === 1 ? 10.8 : colIndex === 2 ? 9.8 : 10.5,'
        );

        // Status cell generated by the approved layout.
        block = block.replace(
          /(rowStatus,[\s\S]{0,180}?size:)\s*\d+(?:\.\d+)?(,\s*\n\s*bold:\s*true,)/g,
          '$1 10.0$2'
        );

        next = next.slice(0, rankingStart) + block + next.slice(section3Start);
      }

      // Section 3: make Topic header and row numbers as readable as the rest of the table.
      const topicStart = next.indexOf('section("3. TEAM TOPIC PERFORMANCE")');
      const topicEnd = next.indexOf('section("4. PAYMENT CERTIFICATION")', topicStart);
      if (topicStart >= 0 && topicEnd > topicStart) {
        let block = next.slice(topicStart, topicEnd);

        // Use the full 180 mm table width and reserve enough room for the complete Topic header.
        block = block.replace(
          /const topicHeaders: Array<\[string, number\]> = \[[\s\S]*?\n\s*\];/,
          `const topicHeaders: Array<[string, number]> = [\n    ["Topic", 22],\n    ["Description", 101],\n    ["Avg Score", 17],\n    ["Max", 11],\n    ["Avg %", 13],\n    ["Status", 16],\n  ];`
        );

        block = block.replace(
          /size:\s*label\s*===\s*"Status"\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: label === "Status" ? 9.8 : 10.4,'
        );

        // Topic row index (1-4) used to remain at 6.2 pt even after the other cells were enlarged.
        block = block.replace(
          /(drawTableCell\(x,\s*y,\s*topicHeaders\[0\]\[1\],\s*rowH,\s*topic\.code,\s*\{[\s\S]{0,120}?size:)\s*\d+(?:\.\d+)?(,)/g,
          '$1 9.8$2'
        );

        block = block.replace(
          /(combinedTopicTitle,[\s\S]{0,180}?size:)\s*\d+(?:\.\d+)?(,)/g,
          '$1 10.0$2'
        );
        block = block.replace(/size:\s*6\.9,/g, 'size: 9.8,');
        block = block.replace(
          /text\(status,\s*x \+ statusWCell \/ 2,\s*y \+ 6\.1,\s*\d+(?:\.\d+)?,/g,
          'text(status, x + statusWCell / 2, y + 6.1, 9.5,'
        );

        next = next.slice(0, topicStart) + block + next.slice(topicEnd);
      }

      return next === code ? null : { code: next, map: null };
    },
  };
}
