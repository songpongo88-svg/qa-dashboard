export function signaturePaymentPdfLargeFontPatch() {
  return {
    name: "signature-payment-pdf-large-font",
    transform(code, id) {
      if (!id.replace(/\\/g, "/").endsWith("/src/SignatureCenterMockup.tsx")) return null;
      if (!code.includes('section("2. AGENT MONTHLY RANKING & PAYMENT DETAILS")')) return null;

      let next = code;

      // Section 2: force every ranking-table font rule regardless of its previous numeric value.
      const section2Start = next.indexOf('section("2. AGENT MONTHLY RANKING & PAYMENT DETAILS")');
      const section3Start = next.indexOf('section("3. TEAM TOPIC PERFORMANCE")', section2Start);
      if (section2Start >= 0 && section3Start > section2Start) {
        let block = next.slice(section2Start, section3Start);

        // Header: Seq / Agent / Document Ref. / Cases / Avg / Grade / Incentive / Status
        block = block.replace(
          /size:\s*label\s*===\s*"Document Ref\."\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: label === "Document Ref." ? 10.3 : 11.0,'
        );

        // Body: Agent, Document Ref. and every numeric/payment column.
        block = block.replace(
          /size:\s*colIndex\s*===\s*1\s*\?\s*\d+(?:\.\d+)?\s*:\s*colIndex\s*===\s*2\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: colIndex === 1 ? 10.8 : colIndex === 2 ? 9.8 : 10.5,'
        );

        // Status cell generated by the approved layout.
        block = block.replace(
          /(rowStatus,[\s\S]{0,180}?size:)\s*\d+(?:\.\d+)?(,\s*\n\s*bold:\s*true,)/g,
          '$1 10.0$2'
        );

        next = next.slice(0, section2Start) + block + next.slice(section3Start);
      }

      // Section 3: apply the same approach so Topic table is readable at 100% too.
      const topicStart = next.indexOf('section("3. TEAM TOPIC PERFORMANCE")');
      const topicEnd = next.indexOf('section("4. PAYMENT CERTIFICATION")', topicStart);
      if (topicStart >= 0 && topicEnd > topicStart) {
        let block = next.slice(topicStart, topicEnd);

        block = block.replace(
          /size:\s*label\s*===\s*"Status"\s*\?\s*\d+(?:\.\d+)?\s*:\s*\d+(?:\.\d+)?,/g,
          'size: label === "Status" ? 9.8 : 10.4,'
        );
        block = block.replace(
          /(combinedTopicTitle,[\s\S]{0,180}?size:)\s*\d+(?:\.\d+)?(,)/g,
          '$1 10.0$2'
        );
        block = block.replace(/size:\s*6\.9,/g, 'size: 9.8,');
        block = block.replace(
          /text\(status,\s*x \+ statusWCell \/ 2,\s*y \+ 6\.1,\s*\d+(?:\.\d+)?,/g,
          'text(status, x + statusWCell / 2, y + 6.1, 9.5,'
        );

        next = next.slice(0, topicStart) + block + next.slice(topicEnd);
      }

      return next === code ? null : { code: next, map: null };
    },
  };
}
