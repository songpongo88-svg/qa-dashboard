// Runs ONLY against a disposable CI PostgreSQL database (not qa_dashboard_lab).
import assert from 'node:assert/strict';
import pg from 'pg';
import { stageQaEvaluationWrite } from '../server/qaCutoverPgWriter.js';
import { QaCutoverBlocked } from '../server/qaCutoverWritePolicy.js';

if (process.env.QA_PG_ISOLATED_TEST !== '1') throw Error('Refusing to run outside isolated test mode');
const connectionString=process.env.QA_TEST_DATABASE_URL;
if(!connectionString)throw Error('Missing disposable PostgreSQL test connection');
const pool=new pg.Pool({connectionString, max:2, connectionTimeoutMillis:5000});
try {
  const identity=await pool.query('SELECT current_database() AS name');
  assert.equal(identity.rows[0].name,'qa_cutover_ci_test','Refusing any non-disposable database');
  await pool.query('CREATE SCHEMA qa_cutover_stage');
  await pool.query(`CREATE TABLE qa_cutover_stage.evaluations(
    evaluation_id text PRIMARY KEY, record jsonb NOT NULL, version integer NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now())`);
  await pool.query(`CREATE TABLE qa_cutover_stage.operations(
    operation_id text PRIMARY KEY, request_hash text NOT NULL, evaluation_id text NOT NULL,
    response jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now())`);
  await pool.query(`CREATE TABLE qa_cutover_stage.audit(
    audit_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id text UNIQUE NOT NULL, evaluation_id text NOT NULL,
    version integer NOT NULL, created_at timestamptz NOT NULL DEFAULT now())`);

  const principal=()=>({
    verificationSource:'trusted-server-session-validator',
    session:{verified:true,status:'active',role:'Quality Assurance',username:'qa_operator',
      expiresAt:new Date(Date.now()+3600000).toISOString()},
    environment:'isolated-local-fixture',fixtureAuthorizedByServer:true,production:false,
    authoritativeScope:{agentName:'Sample Agent',monthKey:'2026-11'},
    signatureLock:{source:'trusted-server',verified:true,scopeKey:'sample agent::2026-11',locked:false},
    appealHold:{source:'trusted-server',verified:true,active:false},
    editLease:{source:'trusted-server',verified:true,valid:true,username:'qa_operator',evaluationId:'synthetic-qa-1'},
  });
  const value={id:'synthetic-qa-1',caseId:'DEMO0001',evaluationMonthKey:'2026-11',
    evaluationType:'case',agentName:'Sample Agent',finalScore:85,topics:[],evaluatorUsername:'qa_operator'};
  const create={action:'create',operationId:'fixture-create-1',evaluationId:value.id,
    expectedVersion:0,record:value};
  assert.equal((await stageQaEvaluationWrite(pool,create,principal())).version,1);
  assert.equal((await stageQaEvaluationWrite(pool,create,principal())).replay,true);
  await assert.rejects(stageQaEvaluationWrite(pool,{...create,record:{...value,finalScore:88}},principal()),
    error=>error instanceof QaCutoverBlocked&&error.code==='operation_reuse_conflict');
  const update={action:'update',operationId:'fixture-update-1',evaluationId:value.id,
    expectedVersion:1,record:{...value,finalScore:84}};
  assert.equal((await stageQaEvaluationWrite(pool,update,principal())).version,2);
  await assert.rejects(stageQaEvaluationWrite(pool,{...update,operationId:'fixture-stale-1',
    record:{...value,finalScore:99}},principal()),
    error=>error instanceof QaCutoverBlocked&&error.code==='stale_version');
  await assert.rejects(stageQaEvaluationWrite(pool,{...update,operationId:'fixture-locked-1',expectedVersion:2}, {
    ...principal(),signatureLock:{...principal().signatureLock,locked:true},
  }),error=>error instanceof QaCutoverBlocked&&error.code==='monthly_results_locked_or_unverified');
  const del={action:'delete',operationId:'fixture-delete-1',evaluationId:value.id,expectedVersion:2};
  assert.equal((await stageQaEvaluationWrite(pool,del,principal())).version,3);
  assert.equal((await stageQaEvaluationWrite(pool,del,principal())).replay,true);
  const current=await pool.query('SELECT evaluation_id,record,version FROM qa_cutover_stage.evaluations');
  assert.equal(current.rows.length,1);
  assert.equal(current.rows[0].record.finalScore,84);
  assert.ok(current.rows[0].record.deletedAt,'delete must preserve a tombstone');
  assert.equal(current.rows[0].version,3);
  const ops=await pool.query('SELECT count(*)::int AS n FROM qa_cutover_stage.operations');
  const audit=await pool.query('SELECT count(*)::int AS n FROM qa_cutover_stage.audit');
  assert.equal(ops.rows[0].n,3);
  assert.equal(audit.rows[0].n,3);
  console.log('PASS: PostgreSQL 17 real transaction integration — 3 successful stage operations, replay-safe, stale-lock denied, source unchanged');
} finally {
  await pool.end();
}
