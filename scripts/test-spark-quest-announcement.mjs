import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (path) => readFileSync(new URL("../" + path, import.meta.url), "utf8");

const art = read("src/SparkQuestAnnouncement.tsx");
const css = read("src/SparkQuestAnnouncement.css");
const hub = read("src/AnnouncementHub.tsx");
const app = read("src/App.tsx");
const quests = read("src/SparksWelcomeQuests.tsx");
assert.match(art, /SPARK_ANNOUNCEMENT_END = "2026-12-25"/);
assert.match(art, /timeZone: "Asia\/Bangkok"/);
assert.match(art, /100–1,000 QA Sparks/);
assert.match(art, /150–800 QA Sparks/);
assert.match(art, /Welcome Fruit Reward/);
assert.match(art, /The Spark Journey/);
assert.match(art, /data-spark-quest-join="true"/);
assert.match(art, /data-spark-quest-inbox-join="true"/);
assert.match(art, /role="link" tabIndex=\{0\}/, "the artwork itself must be clickable");
assert.match(art, /closest\("button"\)/, "button clicks must not navigate twice");
assert.ok(art.includes("markDismissed(username, sessionId)"));
assert.match(art, /dismissedForLogin/);
assert.match(art, /hasUnclaimedSparkQuests/);
assert.match(art, /forceRefresh: true/);
assert.ok(art.includes("!account.firstLogin || !account.sparkJourney2026"));
assert.ok(art.includes("eligibility.sessionKey !== sessionKey"));
assert.ok(art.includes('eligibility.status !== "incomplete"'));
assert.match(art, /localStorage/);
assert.doesNotMatch(art, /claimSparkJourneySparks|claimFirstLoginSparks|Math\.random\(/, "merely clicking the announcement must not award Sparks");
assert.match(hub, /<SparkQuestAnnouncementPopup username=\{currentUsername\}/);
assert.match(hub, /sessionId=\{currentUser\.sessionId \|\| ""\}/);
assert.match(hub, /<SparkQuestAnnouncementInbox onJoin=/);
assert.match(hub, /onNavigateToSparks\(\)/);
assert.match(hub, /blocked=\{!shortcutVisible \|\| hubOpen \|\| Boolean\(popupMessage\)\}/, "announcement popup must not cover existing urgent notices");
assert.match(app, /onNavigateToSparks=\{\(\) => navigateToTab\("qa-sparks"\)\}/, "same-page navigation must preserve the QA login");
assert.match(quests, /getSparksAccount\(username/, "eligibility must come from existing wallet");
assert.match(quests, /!account\.firstLogin/);
assert.match(quests, /!account\.sparkJourney2026/);
assert.match(css, /spark-promo-modal-backdrop/);
console.log("PASS QA Sparks clickable announcement: one popup per incomplete login, permanent inbox CTA, same-page authorized navigation, Bangkok expiry, and no reward on click");
