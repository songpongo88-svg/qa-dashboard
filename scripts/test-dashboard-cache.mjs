import assert from 'node:assert/strict';
import {mkdtemp,writeFile,rm} from 'node:fs/promises';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
import {build} from 'esbuild';
import {JSDOM} from 'jsdom';
import {IDBFactory} from 'fake-indexeddb';
const work=await mkdtemp(resolve('.dashboard-cache-test-'));
const dom=new JSDOM('',{url:'https://qa.test'});globalThis.window=dom.window;
Object.defineProperty(window,'indexedDB',{value:new IDBFactory(),configurable:true});
const file=resolve(work,'cache.mjs');
await build({entryPoints:['src/dashboardRecoveryCache.ts'],outfile:file,bundle:true,platform:'node',format:'esm',logLevel:'silent'});
const cache=await import(pathToFileURL(file));
const key=scope=>'qa-dashboard:recovery-snapshot:v1:'+encodeURIComponent(scope);
const snapshot=(id,time=Date.now())=>({cachedAt:time,cases:[{caseId:id}],noCaseEvaluations:[],appealMergeCount:0});
try{
 const scope='qa|quality assurance|team a',other='other|quality assurance|team a';
 cache.saveDashboardRecoverySnapshot(scope,snapshot('AA111111'));
 assert.equal(cache.readDashboardRecoverySnapshot(scope).cases[0].caseId,'AA111111');
 window.sessionStorage.clear();
 assert.equal(cache.readDashboardRecoverySnapshot(scope).cases[0].caseId,'AA111111','fresh tab restores the same account from durable storage');
 assert.equal(await cache.readDashboardRecoverySnapshotForView(other),null,'never reuse another account snapshot');
 const stale=Date.now()-2*24*60*60*1000;
 const staleScope='stale|quality assurance|team a';
 cache.saveDashboardRecoverySnapshot(staleScope,snapshot('AA222222',stale));
 assert.equal(cache.readDashboardRecoverySnapshot(staleScope),null,'old data is not treated as a fresh snapshot');
 assert.equal((await cache.readDashboardRecoverySnapshotForView(staleScope)).cases[0].caseId,'AA222222','old snapshots remain available explicitly for read-only display');
 // A later partial read cannot replace the earlier 110-case equivalent in any storage.
 const biggerScope='historical|quality assurance|team a';
 const full={...snapshot('AA111111',Date.now()-30_000),cases:[{caseId:'AA111111'},{caseId:'AA222222'},{caseId:'AA333333'}]};
 cache.saveDashboardRecoverySnapshot(biggerScope,full);
 cache.saveDashboardRecoverySnapshot(biggerScope,{...snapshot('AA111111'),cachedAt:Date.now()});
 assert.equal((await cache.readDashboardRecoverySnapshotForView(biggerScope)).cases.length,3,'partial refresh keeps all earlier cases for recovery');
 assert.equal(cache.readDashboardRecoverySnapshot(biggerScope).cases.length,3,'Web Storage also keeps the larger recovery copy');
 const bigScope='large|quality assurance|';
 const big={...snapshot('AA333333'),cases:Array.from({length:500},(_,index)=>({caseId:'AA'+index,caseDescription:'x'.repeat(8000)}))};
 cache.saveDashboardRecoverySnapshot(bigScope,big);
 assert.equal(window.sessionStorage.getItem(key(bigScope)),null,'large data does not exhaust Web Storage');
 assert.equal(window.localStorage.getItem(key(bigScope)),null);
 const recovered=await cache.readDashboardRecoverySnapshotForView(bigScope);
 assert.equal(recovered.cases.length,500,'IndexedDB retains complete snapshots above the old 3.5 MB limit');
 assert.equal(recovered.cases[499].caseDescription.length,8000);
 cache.saveDashboardRecoverySnapshot(bigScope,{...big,cases:[]});
 assert.equal((await cache.readDashboardRecoverySnapshotForView(bigScope)).cases.length,500,'an empty or failed load cannot erase the previous complete copy');
 const blockedScope='blocked|quality assurance|';
 const local=Object.getOwnPropertyDescriptor(window,'localStorage'),session=Object.getOwnPropertyDescriptor(window,'sessionStorage');
 Object.defineProperty(window,'localStorage',{configurable:true,get(){throw new Error('blocked');}});
 Object.defineProperty(window,'sessionStorage',{configurable:true,get(){throw new Error('blocked');}});
 cache.saveDashboardRecoverySnapshot(blockedScope,snapshot('AA444444'));
 assert.equal((await cache.readDashboardRecoverySnapshotForView(blockedScope)).cases[0].caseId,'AA444444','Web Storage failure still permits IndexedDB recovery');
 Object.defineProperty(window,'localStorage',local);Object.defineProperty(window,'sessionStorage',session);
 window.localStorage.setItem(key(other),JSON.stringify({...snapshot('AA555555'),cachedAt:Date.now()+1000}));
 assert.equal(await cache.readDashboardRecoverySnapshotForView(other),null,'future or malformed timestamps cannot enter the view');
 console.log('PASS Dashboard recovery cache: account isolation, new tab, stale read-only data, 4 MB complete IndexedDB snapshots, storage failures and no empty overwrite.');
}finally{dom.window.close();await rm(work,{recursive:true,force:true});}
