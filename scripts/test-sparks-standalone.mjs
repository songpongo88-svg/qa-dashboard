import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read=path=>readFileSync(new URL("../"+path,import.meta.url),"utf8");
const main=read("src/main.tsx");
const entry=read("src/SparksStandalone.tsx");
const email=read("src/SparksEmailAuth.tsx");
const sparks=read("src/QASparks.tsx");
const api=read("api/sparks-admin.js");
assert.match(main,/new URLSearchParams\(window\.location\.search\)\.get\("sparks"\) === "1"/);
assert.match(main,/sparksStandalone\s*\?\s*<React\.StrictMode><RootErrorBoundary><SparksStandalone \/>/,"standalone must not render the QA Dashboard login");
assert.match(main,/Boolean\(new URLSearchParams\(window\.location\.hash\.replace\(\/\^#\/, ""\)\)\.get\("access_token"\)\)/,"Supabase Magic Link callback at preview root should open Sparks");
assert.match(email,/setRateLimited\(true\)/,"email rate limit must throttle repeat sends");
assert.match(entry,/<SparksEmailAuth onVerified=\{setActor\}/,"Sparks portal requires verified Supabase email");
assert.match(entry,/verifiedSparksActor=\{actor\}/,"Sparks UI must receive server-verified identity");
assert.match(email,/if\(username && String\(payload\.actor\.username\)/,"embedded QA path must still require username match");
assert.match(email,/\/auth\/v1\/otp\?redirect_to=/,"OTP must send redirect_to as a query parameter, not in JSON");
assert.doesNotMatch(email,/email_redirect_to:/,"invalid redirect property must not recur");
assert.match(sparks,/sparksAllowed = !emailAuthEnabled/,"Wallet must not read before email verification");
assert.match(api,/originKind !== "same-origin"/,"cookie-authenticated Sparks API denies cross-origin requests");
assert.match(email,/data-sparks-otp-in-place="true"/,"Sparks confirmation code must be entered in the active tab");
assert.match(email,/pendingEmail/,"verify against the email address that received the OTP");
assert.ok(email.includes("maxLength={8}"),"OTP field supports 6–8 numeric digits");
assert.match(email,/type:"email"/,"OTP confirms email token without Magic Link navigation");
assert.match(email,/ยืนยันและเข้าใช้ Sparks ในแท็บนี้/,"explicit same-tab verification action");
assert.doesNotMatch(email,/หรือกดลิงก์ในอีเมล/,"remove separate link instruction");
assert.match(email,/credentials:"same-origin",cache:"no-store"/,"existing Sparks session restored through secure same-origin cookie");
assert.match(email,/Session QA Sparks หมดอายุแล้ว/,"OTP requested again when session expires");
assert.match(entry,/window.addEventListener\("focus",validate\)/,"standalone rechecks session when browser regains focus");
assert.match(sparks,/\[emailAuthEnabled,sparksAllowed,active,username\]/,"embedded Sparks tab rechecks on re-entry");
assert.match(email,/setRetrySeconds\(60\)/,"server 429 must apply an anti-spam cooldown before allowing retry");
assert.match(email,/if\(busy\|\|retrySeconds>0\)return/,"repeat requests are prevented until cooldown expires");
assert.match(email,/setSent\(false\);setPendingEmail\(""\);setCode\(""\)/,"failed send must clear unsent OTP state");
assert.match(email,/\{sent && <form onSubmit=\{verify\}/,"only a successful OTP send may display the verification field");
assert.match(email,/sent\|\|rateLimited\?"ส่งรหัสใหม่"/,"users can explicitly request a fresh OTP");
assert.match(email,/ครั้งนี้ยังไม่มี OTP ใหม่ถูกส่ง/,"never imply a new OTP was sent after Supabase 429");
assert.doesNotMatch(email,/สามารถใช้รหัสจากอีเมลล่าสุด|รหัสจากอีเมลฉบับก่อนหน้า/,"do not instruct users to reuse an old code");
assert.match(entry,/qa:sparks:supabase-login:/,"verified standalone users retain their Supabase preference");
assert.match(sparks,/data-sparks-supabase-optin="true"/,"embedded Sparks exposes opt-in to every staff member");
assert.match(sparks,/data-sparks-employee-email-login="true"/,"OTP remains in the existing dashboard tab");
assert.ok(sparks.includes("setVerifiedActor(actor)"),"only verified server identity opens the wallet");
console.log("PASS independent Sparks portal: no QA Dashboard login mount, email verification, username match and CSRF denial");
