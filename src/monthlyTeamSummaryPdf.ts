import { jsPDF } from "jspdf";
import { registerTHSarabunNew } from "./THSarabunNew-jsPDF";
import { scoreToGrade } from "./lib/scoreIncentivePolicy";
import { canonicalAgentIdentityKey } from "./lib/agentIdentity";
import { formatPdfDateTime } from "./lib/pdfDates";

type SummaryCase = {
  agent: string;
  monthKey: string;
  finalScore: number;
  reviewStatus?: string;
};

export function summarizeMonthlyCases(cases: readonly SummaryCase[], monthKey: string) {
  const averageScore = cases.length ? cases.reduce((sum, item) => sum + item.finalScore, 0) / cases.length : 0;
  return { caseCount: cases.length, averageScore, grade: scoreToGrade(averageScore, monthKey),
    revisedCount: cases.filter(item => item.reviewStatus === "Revised").length };
}

export function createMonthlyTeamSummaryPdf({ cases, monthKey, agentLabel, teamLabel, generatedBy, generatedAt = new Date() }: {
  cases: readonly SummaryCase[];
  monthKey: string;
  agentLabel: string;
  teamLabel: string;
  generatedBy: string;
  generatedAt?: Date;
}) {
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(monthKey)) throw new Error("กรุณาเลือกเดือนที่ต้องการออกรายงาน");
  const monthlyCases = cases.filter(item => item.monthKey === monthKey);
  const summary = summarizeMonthlyCases(monthlyCases, monthKey);
  const monthLabel = new Date(`${monthKey}-01T12:00:00`).toLocaleDateString("en-GB", { month: "long", year: "numeric" });
  const pdf = new jsPDF({ orientation: "portrait", unit: "mm", format: "a4" });
  registerTHSarabunNew(pdf);
  pdf.setFont("THSarabunNew", "bold");
  pdf.setFontSize(24);
  pdf.setTextColor("#36265c");
  pdf.text("Monthly Team Summary", 14, 19);
  pdf.setFont("THSarabunNew", "normal");
  pdf.setFontSize(13);
  pdf.setTextColor("#64748b");
  pdf.text("Robinhood QA - Quality Monitoring Workspace", 14, 26);
  pdf.setDrawColor("#ddd6ee");
  pdf.line(14, 30, 196, 30);
  pdf.setFont("THSarabunNew", "bold");
  pdf.setTextColor("#36265c");
  pdf.setFontSize(15);
  pdf.text("Current Scope", 14, 38);
  pdf.setFont("THSarabunNew", "normal");
  pdf.setFontSize(13);
  pdf.setTextColor("#334155");
  const scopeLines = pdf.splitTextToSize(`Agent: ${agentLabel}    Team: ${teamLabel}\nMonth: ${monthLabel}    Week: All Weeks    Year: ${monthKey.slice(0, 4)}\nGenerated by: ${generatedBy}`, 182);
  pdf.text(scopeLines, 14, 45);
  const metricsY = 45 + scopeLines.length * 5 + 3;
  pdf.text(`Cases: ${summary.caseCount}    Average Score: ${summary.averageScore.toFixed(2)}    Grade: ${summary.grade}    Revised: ${summary.revisedCount}`, 14, metricsY);
  pdf.setTextColor("#64748b");
  pdf.text(`Generated at: ${formatPdfDateTime(generatedAt)}`, 14, metricsY + 6);
  const drawTable = (head: string[], body: Array<Array<string | number>>, startY: number) => {
    const widths = [74, 23, 39, 23, 23];
    let y = startY;
    const drawRow = (values: Array<string | number>, heading: boolean, stripe = false) => {
      pdf.setFont("THSarabunNew", heading ? "bold" : "normal");
      pdf.setFontSize(13);
      const lines = values.map((value, index) => pdf.splitTextToSize(String(value), widths[index] - 6) as string[]);
      const height = Math.max(9, ...lines.map(value => value.length * 4.7 + 4));
      pdf.setFillColor(heading ? "#6d4a99" : stripe ? "#f7f4fb" : "#ffffff");
      pdf.rect(14, y, 182, height, "F");
      pdf.setTextColor(heading ? "#ffffff" : "#334155");
      let x = 14;
      lines.forEach((value, index) => { pdf.text(value, x + 3, y + 6); x += widths[index]; });
      pdf.setDrawColor("#e8e2f0");
      pdf.line(14, y + height, 196, y + height);
      y += height;
    };
    if (y > 260) { pdf.addPage(); y = 18; }
    drawRow(head, true);
    body.forEach((values, index) => {
      const lines = values.map((value, column) => pdf.splitTextToSize(String(value), widths[column] - 6) as string[]);
      const height = Math.max(9, ...lines.map(value => value.length * 4.7 + 4));
      if (y + height > 276) { pdf.addPage(); y = 18; drawRow(head, true); }
      drawRow(values, false, index % 2 === 0);
    });
    return y;
  };
  const summaryBottom = drawTable(["Month", "Cases", "Average Score", "Grade", "Revised"],
    [[monthLabel, summary.caseCount, summary.averageScore.toFixed(2), summary.grade, summary.revisedCount]], metricsY + 12);
  const agents = new Map<string, { name: string; cases: SummaryCase[] }>();
  monthlyCases.forEach(item => {
    const key = canonicalAgentIdentityKey(item.agent);
    const entry = agents.get(key) || { name: item.agent, cases: [] };
    entry.cases.push(item);
    agents.set(key, entry);
  });
  const rows = [...agents.values()].sort((a, b) => a.name.localeCompare(b.name, "th")).map(agent => {
    const result = summarizeMonthlyCases(agent.cases, monthKey);
    return [agent.name, result.caseCount, result.averageScore.toFixed(2), result.grade, result.revisedCount];
  });
  if (rows.length) {
    drawTable(["Agent", "Cases", "Average Score", "Grade", "Revised"], rows, summaryBottom + 9);
  } else {
    pdf.text("No evaluated cases for this month and scope.", 14, summaryBottom + 10);
  }
  for (let page = 1; page <= pdf.getNumberOfPages(); page++) {
    pdf.setPage(page);
    pdf.setFontSize(11);
    pdf.setTextColor("#94a3b8");
    pdf.text(`${monthLabel} | Page ${page} / ${pdf.getNumberOfPages()}`, 196, 289, { align: "right" });
  }
  return { pdf, fileName: `Monthly_Team_Summary_${monthKey}.pdf`, summary };
}
